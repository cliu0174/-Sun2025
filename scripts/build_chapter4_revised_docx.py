    add_p(doc, "本文未将LSTM替换为更复杂的Transformer结构，主要基于两个考虑。第一，当前研究问题的核心不是长文本式全局依赖建模，而是中等长度生命周期序列中的退化趋势提取，LSTM已经能够提供足够的状态记忆能力。第二，Transformer虽然通过自注意力机制增强全局关联建模能力[31]，但在标签稀缺条件下更容易受到数据规模、正则化和超参数设置影响。因而本文将Transformer作为文献背景和可能扩展方向，而不是当前主线模型。")

    add_h(doc, "4.3.4 基于软单调性的物理一致性弱监督", 2)
    add_p(doc, "锂离子电池在稳定退化阶段的SOH整体应呈非上升趋势。该现象来源于活性锂损失、活性材料损失、SEI膜增长和内阻增加等不可逆退化过程[22,23]。基于这一宏观先验，本文引入延迟激活的软单调约束。该约束并不要求所有相邻循环严格单调，而是允许一定容忍范围内的局部波动，仅对超过容忍阈值的非物理上升进行惩罚。")
    add_eq(doc, "公式4-3", r"L_mono = mean_{(i,t) in P} max(0, yhat_{t+1}^{(i)} - yhat_t^{(i)} - epsilon)")
    add_p(doc, "其中，P表示满足约束激活条件的相邻循环对集合，epsilon为容忍因子。考虑到电池寿命早期可能存在容量活化、测试噪声或短暂平台波动，本文采用延迟激活策略，仅在循环索引超过给定阈值后施加单调约束。")
    add_note(doc, "图4-5  锂离子电池生命周期早期容量回升现象示意图（图片占位）")
    add_p(doc, "在完整标签条件下，软单调约束可视为对数据拟合项的辅助正则化；但在部分生命周期监督条件下，它具有更关键的机制意义。对于无标签循环，数据误差项不提供梯度，而软单调约束仍可基于相邻循环预测关系产生训练信号。因此，该约束不仅提高预测轨迹的物理合理性，也为无标签生命周期区间提供结构性弱监督。物理信息机器学习和PINN研究表明，将物理规律作为损失项或结构约束嵌入模型，有助于在小样本或不完全观测条件下提升泛化和可解释性[32-34]。")
    add_p(doc, "软单调约束采用延迟激活而非全生命周期强制约束，是因为实际电池在早期循环中可能出现短暂容量回升或平台波动。这类现象可能来源于电极润湿、活化过程、测试误差或温度微小扰动。若从第一个循环开始施加强单调约束，模型可能被迫忽略这些真实存在的早期变化，反而降低拟合质量。因此，本文将单调约束主要作用于稳定退化阶段，使物理先验与数据特性保持一致。")
    add_p(doc, "此外，本文采用“软”约束而非硬约束。硬约束要求每个相邻循环预测值严格不升高，虽然物理含义清晰，但在含噪测量数据和复杂工况下过于刚性。软约束通过容忍阈值允许小幅局部波动，只惩罚超过阈值的非物理上升。这种设计更符合工程数据的实际形态，也有助于避免物理约束与数据拟合目标发生剧烈冲突。")
    add_p(doc, "需要强调的是，本文的物理一致性约束属于轻量级物理先验，而非完整电化学模型求解。完整PINN通常需要明确的控制方程、边界条件或退化动力学方程；而实际BMS数据中，许多内部状态不可直接观测，完整电化学参数辨识成本较高。本文选择容量退化方向这一更稳定、可迁移的宏观先验，是为了在工程可实现性与物理解释性之间取得平衡。该策略不追求重建全部电化学机理，而是将最可靠的退化规律转化为训练约束。")

    add_h(doc, "4.3.5 综合损失函数与评价指标", 2)
    add_p(doc, "模型训练目标由数据监督损失和物理一致性损失组成，如公式4-4所示。")
    add_eq(doc, "公式4-4", r"L_total = L_data + lambda_mono L_mono")
    add_p(doc, "其中，L_data仅在有标签循环上计算，如公式4-5所示。")
    add_eq(doc, "公式4-5", r"L_data = sum_i sum_t m_t^(i)(yhat_t^(i)-y_t^(i))^2 / sum_i sum_t m_t^(i)")
    add_p(doc, "该损失设计体现了本文方法的核心逻辑：有标签循环通过数据损失学习准确的SOH数值映射，无标签循环通过物理一致性约束参与退化方向学习。评价指标包括RMSE、MAE、R²以及单调违反率。其中，RMSE和MAE衡量数值误差，R²衡量整体拟合能力，单调违反率衡量预测轨迹对退化单调性先验的遵循程度。")
    add_p(doc, "在优化过程中，数据误差项和物理一致性项承担不同职责。数据误差项决定模型输出的绝对SOH数值尺度，是保证预测精度的主要来源；物理一致性项决定预测序列的可行演化方向，是保证未标注区间稳定性的关键来源。若物理权重过小，无标签区间约束不足；若物理权重过大，模型可能牺牲局部拟合精度以满足过强的单调性要求。因此，物理权重需要通过验证集或消融实验确定，并在论文中明确讨论其适用边界。多任务学习中常通过不确定性或可学习权重平衡多个损失项[35]，但在本文低标签场景下，固定权重加消融分析更便于解释物理约束的真实贡献。")
    add_p(doc, "除常规误差指标外，本文引入单调违反率作为物理一致性评价指标。该指标统计同一电池预测序列中出现非物理上升的比例，可用于衡量模型输出是否符合容量退化的基本趋势。需要注意的是，单调违反率不能单独代表模型优劣；过低的违反率可能来自过度平滑，而非真实精度提升。因此，本文将MAE、RMSE、R²和单调违反率联合使用，以同时评价数值精度和物理可信度。")
    add_p(doc, "指标解释应避免“误差越低即完全更优”的单一判断。SOH估计面向的是安全运行和寿命管理，模型输出不仅要平均误差小，还要在退化方向、局部波动和未见电池上保持可信。尤其在部分生命周期监督场景中，某些模型可能在有标签区间误差较低，但在无标签区间产生明显非物理波动；另一些模型平均误差略高，却能给出更平滑和更符合退化规律的轨迹。因此，本文将数值误差、物理一致性和轨迹可解释性并列为评价对象。")

